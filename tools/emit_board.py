TEMPLATE_KEYS = ("general", "paper", "layers", "setup")


def fmt(v):
    """Format a number the way KiCad does (no trailing zeros)."""
    if isinstance(v, str):
        return v
    if float(v) == int(v):
        return str(int(v))
    return f"{v:.6f}".rstrip("0").rstrip(".")


def load_library():
    lib = {}
    for fn in sorted(os.listdir(LIBDIR)):
        if fn.endswith(".kicad_mod"):
            fp = ks.parse(open(os.path.join(LIBDIR, fn), encoding="utf-8").read())
            lib[fp[1]] = fp
    return lib


def set_child(node, key, value):
    for i, item in enumerate(node):
        if isinstance(item, list) and item and item[0] == key:
            node[i] = value
            return
    node.append(value)


def instantiate(libfp, item, netnum):
    """Clone a library footprint into a placed, netted board footprint."""
    out = [libfp[0], libfp[1],
           ["layer", ks.Quoted("F.Cu")],
           ["uuid", ks.Quoted(str(uuid.uuid4()))],
           ["at", fmt(item["x"]), fmt(item["y"]), fmt(item.get("rot", 0))]]

    for ch in libfp[2:]:
        if not isinstance(ch, list):
            continue
        key = ch[0]
        if key in ("layer", "at", "uuid", "net"):
            continue
        node = copy.deepcopy(ch)
        if key == "property":
            set_child(node, "uuid", ["uuid", ks.Quoted(str(uuid.uuid4()))])
            if node[1] == "Reference":
                node[2] = ks.Quoted(item["ref"])
            elif node[1] == "Value":
                node[2] = ks.Quoted(item["value"])
        elif key == "pad":
            set_child(node, "uuid", ["uuid", ks.Quoted(str(uuid.uuid4()))])
            # existing net element was already dropped by the clone loop above
            net = item["nets"].get(node[1])
            if net:
                node.append(["net", str(netnum[net]), ks.Quoted(net)])
        out.append(node)
    return out


def links_by_ref(plan):
    """Nets that reach a footprint only through a jumper (ratsnest) link."""
    out = {}
    for ref, pin, net in plan["links"]:
        out.setdefault(ref, {})[pin] = net
    return out



# KiCad's parser requires these values to be quoted strings. An unquoted one
# produces a file that round-trips happily through our own reader but that KiCad
# refuses to open, with an error that names only a line number -- so check
# before writing rather than after someone tries to load it.
QUOTED_KEYS = {"generator", "generator_version", "descr", "tags", "uuid",
               "model", "pinfunction", "pintype"}


def needs_quotes(value):
    """Would KiCad's tokeniser choke on this written bare?

    It accepts a bare *symbol* almost anywhere -- `(layer F.Cu)` and bare uuids
    load fine, which is why unquoted ones went unnoticed for so long. What it
    cannot accept is a value that tokenises as a NUMBER where it wants a symbol:
    `(generator_version 9.0)` is the error this check exists for.
    """
    if not isinstance(value, str) or isinstance(value, ks.Quoted):
        return False
    if any(c.isspace() for c in value):
        return True
    try:
        float(value)
        return True
    except ValueError:
        return False


def lint_quoting(node, where="kicad_pcb[0]", problems=None):
    """Walk the tree and report values KiCad requires to be quoted strings."""
    if problems is None:
        problems = []
    if not isinstance(node, list) or not node:
        return problems
    key = node[0] if isinstance(node[0], str) else None

    def flag(what, value):
        if needs_quotes(value):
            problems.append(f"{where}/{what}: {value!r} written bare tokenises wrong")

    if key == "layers":
        for i, v in enumerate(node[1:], 1):
            flag(f"layers[{i}]", v)
    elif key == "layer" and len(node) > 1:
        flag("layer", node[1])
    elif key == "uuid" and len(node) > 1:
        if not isinstance(node[1], ks.Quoted):
            problems.append(f"{where}/uuid: {node[1]!r} must be a quoted uuid")
    elif key == "generator_version" and len(node) > 1:
        # the one KiCad definitely writes as a string, and the one that bit us
        if not isinstance(node[1], ks.Quoted):
            problems.append(f"{where}/generator_version: {node[1]!r} must be quoted")
    elif key in QUOTED_KEYS and len(node) > 1:
        flag(key, node[1])
    elif key in ("footprint", "pad") and len(node) > 1:
        flag(key + "[1]", node[1])
    elif key == "property":
        for i in (1, 2):
            if i < len(node):
                flag(f"property[{i}]", node[i])
    elif key == "net" and len(node) > 2:
        flag("net[2]", node[2])

    for i, ch in enumerate(node):
        if isinstance(ch, list):
            lint_quoting(ch, f"{where}/{key or '?'}[{i}]", problems)
    return problems


def emit(plan, out_path):
    lib = load_library()
    netnum = L.collect_nets(plan)
    extra = links_by_ref(plan)

    template = ks.parse(BOARD_TEMPLATE)
    root = ["kicad_pcb",
            ["version", "20241229"],
            ["generator", ks.Quoted("jaiba-emit_board")],
            ["generator_version", ks.Quoted("9.0")]]
    for key in TEMPLATE_KEYS:
        node = ks.child(template, key)
        if node:
            root.append(copy.deepcopy(node))

    root.append(["net", "0", ks.Quoted("")])
    for name, num in netnum.items():
        root.append(["net", str(num), ks.Quoted(name)])

    for item in plan["footprints"]:
        if item["name"] not in lib:
            raise SystemExit(f"footprint {item['name']!r} missing from {LIBDIR}")
        merged = dict(item)
        merged["nets"] = {**item["nets"], **extra.get(item["ref"], {})}
        root.append(instantiate(lib[item["name"]], merged, netnum))

    for t in plan["tracks"]:
        if "x1" not in t:
            continue
        root.append(["segment",
                     ["start", fmt(t["x1"]), fmt(t["y1"])],
                     ["end", fmt(t["x2"]), fmt(t["y2"])],
                     ["width", fmt(t.get("width", L.TRACK_W))],
                     ["layer", "F.Cu"],
                     ["net", str(netnum[t["net"]])],
                     ["uuid", ks.Quoted(str(uuid.uuid4()))]])

    for x1, y1, x2, y2 in plan["edges"]:
        root.append(["gr_line",
                     ["start", fmt(x1), fmt(y1)],
                     ["end", fmt(x2), fmt(y2)],
                     ["stroke", ["width", fmt(L.EDGE_W)], ["type", "solid"]],
                     ["layer", ks.Quoted("Edge.Cuts")],
                     ["uuid", ks.Quoted(str(uuid.uuid4()))]])

    root.append(["embedded_fonts", "no"])

    problems = lint_quoting(root)
    if problems:
        print("REFUSING TO WRITE -- values KiCad requires to be quoted are not:")
        for msg in problems[:20]:
            print("   " + msg)
        if len(problems) > 20:
            print(f"   ... and {len(problems) - 20} more")
        raise SystemExit(1)

    ks.dump_file(root, out_path)
    return netnum


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT
    plan = L.plan()
    netnum = emit(plan, out)
    print(f"wrote {os.path.relpath(out, REPO)}")
    print(f"  {plan['width']} x {plan['height']} mm, "
          f"{len(plan['footprints'])} footprints, {len(netnum)} nets, "
          f"{len([t for t in plan['tracks'] if 'x1' in t])} segments, "
          f"{len(plan['edges'])} edge cuts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
