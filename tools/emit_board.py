"""
Emit a complete .kicad_pcb from the layout plan, without KiCad.

Normally the board is generated by jaiba-kicad-controlboard.py running inside
KiCad's Scripting Console, which needs the `pcbnew` module (shipped with KiCad,
not with Python). This script produces the same board straight from the plan in
jaiba_board_layout.py, so the project can be regenerated and geometry-checked
anywhere -- including CI or a machine with no KiCad install.

Footprints are read from the project-local library in
kicad-control-board/jaiba.pretty/, which makes the project self-contained: it no
longer depends on KiCad's system libraries or on a hard-coded install path.

Run:  python3 tools/emit_board.py [output.kicad_pcb]
"""

